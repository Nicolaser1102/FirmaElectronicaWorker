WHERE cuo_credito = @AS_CREDITO
and cuo_pagada = 0
and cuo_rubro = rub_rubro
and rub_es_renovacion = 1

IF @@ERROR <> 0
BEGIN
	SET @AS_MSJ = 'PROBLEMAS AL OBTENER LOS GASTOS POR RENOVACION '
	RETURN -1 
END
*/

-- VALIDA VALOR A RENOVARSE Y EL PAGO GENERADO
-- SOLAMENTE SI EL VALOR A LIQUIDAR ES MAYOR A CERO
-- SE GENERA UNA TRANSACCION SOBRE LA OPERACION ANTERIOR
--


IF  @LM_A_LIQUIDAR > 0 AND @AM_VALOR >= 0
BEGIN

	-- PAGO DE CAJA GENERADO PARA PROCESAR LA RENOVACIÓN
	--EXEC sp_cr_tipo_trans_pago_caja @LS_TIPO_TRAN OUT

	EXEC @LI_RET = sp_sl_gastos_renovacion @AS_CREDITO , @LM_GASTOS_RENOVACION OUT, @AS_MSJ OUT, @AI_SIN_FINANCIAMIENTO = 1 
	
	IF @LI_RET < 0  RETURN -1 

	
	IF @LS_TIPO_OPERACION <> 'F'
	BEGIN
		SET @AM_VALOR = @AM_VALOR - @LM_GASTOS_RENOVACION 
	END  
	
	IF @AS_TIPO_TRAN = dbo.f_obtener_parametro_s ('CRPG')
		EXEC sp_cr_tipo_trans_pago_caja @LS_TIPO_TRAN OUT
	ELSE 
		SET @LS_TIPO_TRAN = @AS_TIPO_TRAN
	
	IF  @LS_TIPO_OPERACION = 'F'
	BEGIN
		SET @LM_VALOR_CXC_REFINANCIAMIENTO = 0
		
		SELECT @LM_VALOR_PAGO_REFINANCIAMIENTO = sol_pago_refinanciamiento,
		@LM_VALOR_CXC_REFINANCIAMIENTO = sol_cxc_refinanciamiento
		FROM SL_SOLICITUD
		WHERE sol_solicitud = @LI_SOLICITUD_NUEVA

		SET @LM_VALOR_PAGO_REFINANCIAMIENTO = ISNULL(@LM_VALOR_PAGO_REFINANCIAMIENTO,0)
		SET @LM_VALOR_CXC_REFINANCIAMIENTO = ISNULL(@LM_VALOR_CXC_REFINANCIAMIENTO,0)
		
				
		IF @AM_VALOR <> @LM_VALOR_PAGO_REFINANCIAMIENTO + ISNULL(@LM_GASTOS_RENOVACION,0)
		BEGIN
			SET @AS_MSJ = 'REFINANCIAMIENTO VALOR NO CORRESPONDE CON VALOR DE PAGO INGRESADO EN LA NEGOCIACION' 
			RETURN -1
		END
		
	END	


	IF  @LS_TIPO_OPERACION = 'R' AND isnull(dbo.f_obtener_parametro_b('CR_RENOV_CXC_R'),0) = 1
	BEGIN
		SET @LM_VALOR_CXC_RENOVACION = 0
		
		SELECT @LM_VALOR_PAGO_RENOVACION = sol_pago_renovacion,
		@LM_VALOR_CXC_RENOVACION = sol_cxc_renovacion
		FROM SL_SOLICITUD
		WHERE sol_solicitud = @LI_SOLICITUD_NUEVA
		
		SET @LM_VALOR_PAGO_RENOVACION = ISNULL(@LM_VALOR_PAGO_RENOVACION,0)
		SET @LM_VALOR_CXC_RENOVACION = ISNULL(@LM_VALOR_CXC_RENOVACION,0)
		
		IF @AM_VALOR <> @LM_VALOR_PAGO_RENOVACION + ISNULL(@LM_GASTOS_RENOVACION,0) 
		BEGIN
			SET @AS_MSJ = 'RENOVACION (R) VALOR NO CORRESPONDE CON VALOR DE PAGO INGRESADO EN LA NEGOCIACION' 
			RETURN -1
		END
		
	END	

	/*
	IF  @LS_TIPO_OPERACION = 'T' AND isnull(dbo.f_obtener_parametro_b('CR_RENOV_CXC_T'),0) = 1
	BEGIN
		SET @LM_VALOR_CXC_RENOVACION = 0
		
		SELECT @LM_VALOR_PAGO_RENOVACION = sol_pago_renovacion,
		@LM_VALOR_CXC_RENOVACION = sol_cxc_renovacion
		FROM SL_SOLICITUD
		WHERE sol_solicitud = @LI_SOLICITUD_NUEVA
		
		SET @LM_VALOR_PAGO_RENOVACION = ISNULL(@LM_VALOR_PAGO_RENOVACION,0)
		
		IF @AM_VALOR <> @LM_VALOR_PAGO_RENOVACION 
		BEGIN
			SET @AS_MSJ = 'RENOVACION (T) VALOR NO CORRESPONDE CON VALOR DE PAGO INGRESADO EN LA NEGOCIACION' 
			RETURN -1
		END
		
	END
	*/	

	IF @AM_VALOR > 0 
	BEGIN

		IF @LM_A_LIQUIDAR - @AM_VALOR > 0 AND @LS_TIPO_OPERACION = 'R' AND  isnull(dbo.f_obtener_parametro_b('CR_RENOV_CXC_R'),0) = 1
		BEGIN
		
			SET @LM_VALOR_REFINANCIAR = 0
	
			SET @LM_VALOR_REFINANCIAR = @LM_A_LIQUIDAR - @AM_VALOR - @LM_GASTOS_RENOVACION
	
			SET @LM_VALOR_CXC_RENOVACION = ISNULL(@LM_VALOR_CXC_RENOVACION,0)

			IF @LM_VALOR_REFINANCIAR <> @LM_VALOR_CXC_RENOVACION
			BEGIN
				SET @AS_MSJ = 'VALOR CXC NO CORRESPONDE CON VALOR INGRESADO EN LA NEGOCIACION (R)' 
				RETURN -1
			END
		END 

		/*
		IF @LM_A_LIQUIDAR - @AM_VALOR > 0 AND @LS_TIPO_OPERACION = 'T' AND  isnull(dbo.f_obtener_parametro_b('CR_RENOV_CXC_T'),0) = 1
		BEGIN
		
			SET @LM_VALOR_REFINANCIAR = 0
	
			SET @LM_VALOR_REFINANCIAR = @LM_A_LIQUIDAR - @AM_VALOR - @LM_GASTOS_RENOVACION
	
			SET @LM_VALOR_CXC_RENOVACION = ISNULL(@LM_VALOR_CXC_RENOVACION,0)

			IF @LM_VALOR_REFINANCIAR <> @LM_VALOR_CXC_RENOVACION
			BEGIN
				SET @AS_MSJ = 'VALOR CXC NO CORRESPONDE CON VALOR INGRESADO EN LA NEGOCIACION (T)' 
				RETURN -1
			END
		END
		*/

		SET @LS_REFERENCIA_AUX = SUBSTRING('R.' + @AS_REFERENCIA,1,20) 

		SET @AM_EFECTIVO = @AM_VALOR  

		EXEC @LI_RET =   sp_cr_inserta_transaccion_cr
					@AS_CREDITO = @AS_CREDITO,
					@AS_TIPO_TRANS = @LS_TIPO_TRAN ,
					@AS_MONEDA = @AS_MONEDA ,
					@AM_VALOR = @AM_VALOR ,
					@AM_EFECTIVO = @AM_VALOR ,
					@AM_CHEQUE = 0,
					@AS_OFICINA = @AS_OFICINA,
					@AS_USUARIO = @AS_USUARIO ,
					@AS_MSJ = @AS_MSJ   OUTPUT,
					@AI_TRAN = @AI_TRA_ID  OUTPUT,
					@AB_ABONO_RECALCULO = 0,
					@AS_REFERENCIA = @LS_REFERENCIA_AUX,
					@ADT_FECHA_VALOR = @ADT_FECHA_VALOR,
					@AS_BANCO_DEP = @AI_BANCO_DEP,
					@AS_CUENTA_DEP = @AS_CUENTA_DEP,
					@AB_FORZAR_RECUP_V = 1

		IF @LI_RET = -1
			RETURN -1
			
		EXEC @LI_RET = sp_cr_inserta_renovacion_transaccion @AI_RENOVACION = @LI_RENOVACION,@AI_TRA_ID = @AI_TRA_ID,@AS_MSJ = @AS_MSJ  OUTPUT
		
		IF @LI_RET = -1
			RETURN -1
			
	END
	ELSE
	IF @AM_VALOR < 0 AND @LS_TIPO_OPERACION <> 'F'
	BEGIN
		SET @AS_MSJ = @AS_CREDITO+ ' VALOR LIQUIDAR ' +CONVERT(VARCHAR, @LM_A_LIQUIDAR  )+ ' GASTOS RENOVACION '+CONVERT(VARCHAR, @LM_GASTOS_RENOVACION )+ ' VALOR PAGO '+ CONVERT(VARCHAR, @AM_VALOR)
		RETURN -1
	END	
	
	IF @LM_A_LIQUIDAR - @AM_VALOR > 0 AND @LS_TIPO_OPERACION = 'F' 
	BEGIN
		
		SET @LM_VALOR_REFINANCIAR = 0
	
		SET @LM_VALOR_REFINANCIAR = @LM_A_LIQUIDAR - @AM_VALOR
	
		SET @LS_REFERENCIA_AUX = SUBSTRING('R.' + @AS_REFERENCIA,1,20) 
			
		SET @LM_VALOR_CXC_REFINANCIAMIENTO = ISNULL(@LM_VALOR_CXC_REFINANCIAMIENTO,0)

		IF @LM_VALOR_REFINANCIAR <> @LM_VALOR_CXC_REFINANCIAMIENTO
		BEGIN
			SET @AS_MSJ = 'VALOR CXC NO CORRESPONDE CON VALOR INGRESADO EN LA NEGOCIACION' 
			RETURN -1
		END
	
		SET @LS_TIPO_TRAN = NULL
		
		
		SELECT @LS_TIPO_TRAN = ttr_tipo_tran
		FROM CR_TIPO_TRANSACCION 
		WHERE ttr_es_refinanciamiento = 1 AND 
		ttr_estado = 'A'
		
		

		EXEC @LI_RET =   sp_cr_inserta_transaccion_cr
					@AS_CREDITO = @AS_CREDITO,
					@AS_TIPO_TRANS = @LS_TIPO_TRAN ,
					@AS_MONEDA = @AS_MONEDA ,
					@AM_VALOR = @LM_VALOR_REFINANCIAR,
					@AM_EFECTIVO = 0,
					@AM_CHEQUE = 0,
					@AS_OFICINA = @AS_OFICINA,
					@AS_USUARIO = @AS_USUARIO ,
					@AS_MSJ = @AS_MSJ   OUTPUT,
					@AI_TRAN = @AI_TRA_ID  OUTPUT,
					@AB_ABONO_RECALCULO = 0,
					@AS_REFERENCIA = @LS_REFERENCIA_AUX,
					@ADT_FECHA_VALOR = @ADT_FECHA_VALOR,
					@AS_BANCO_DEP = @AI_BANCO_DEP,
					@AS_CUENTA_DEP = @AS_CUENTA_DEP,
					@AB_FORZAR_RECUP_V = 1 

		IF @LI_RET = -1
			RETURN -1
			
		EXEC @LI_RET = sp_cr_inserta_renovacion_transaccion @AI_RENOVACION = @LI_RENOVACION,@AI_TRA_ID = @AI_TRA_ID,@AS_MSJ = @AS_MSJ  OUTPUT
		
		IF @LI_RET = -1
			RETURN -1
			
		SET @AM_VALOR = @AM_VALOR + @LM_VALOR_REFINANCIAR
	
