CREATE   PROCEDURE [dbo].[sp_cr_renovacion_credito]
@AS_USUARIO 	VARCHAR(15),
@AS_OFICINA	CHAR(4),
@AS_MONEDA	CHAR(1),
@AS_CREDITO 	VARCHAR(20),
@AM_VALOR 	MONEY,
@AM_EFECTIVO 	MONEY,
@AM_CHEQUE 	MONEY,
@AI_TRA_ID 	INT OUTPUT,
@AS_MSJ 	VARCHAR(100) OUTPUT,
@AB_RENOVACION_MANUAL BIT = 1,
@AB_RENOVACION_AUTOMATICA BIT = 0,
@AS_TIPO_TRAN CHAR(3) = NULL,
@AS_REFERENCIA VARCHAR(20) = NULL,
@ADT_FECHA_VALOR DATETIME = NULL,
@AI_BANCO_DEP VARCHAR(20) = NULL,
@AS_CUENTA_DEP VARCHAR(20) = NULL,
@AS_TIPO_DESEMBOLSO CHAR(3) = NULL,
@AS_TIPO_CUENTA_DEP CHAR(2) = NULL 
AS

DECLARE @LS_MONEDA CHAR(1), @LS_TIPO_TRAN CHAR(3), @LI_RET INT,
	@LM_GASTOS MONEY, @LM_RENOVACION MONEY, @LM_SALDO MONEY,
	@LM_SALDO_CR MONEY,@LM_MONTO_SOL MONEY,
	@LI_TRAN INT, @LS_CREDITO VARCHAR(20), @LI_SOLICITUD  INT ,
	@LM_A_LIQUIDAR MONEY , @LS_TIPO_DESEMBOLSO CHAR(2),
	@LS_CREDITO_NUEVO VARCHAR(20),
	@LM_SALDO_CUOTA_CERO MONEY,
	@LS_RUBRO_K CHAR(3),
	@LM_VALORES_ANTERIORES MONEY,
	@LM_GASTOS_RENOVACION MONEY,
	@LM_MONTO_RECIBIR MONEY,
	@LS_PRODUCTO VARCHAR (5),
	@LS_TIPO_OPERACION CHAR(1),
	@LI_SOLICITUD_NUEVA INT,
	@LI_RENOVACION INT,
	@LS_FONDO CHAR(3),
	@LS_SUB_FONDO CHAR(3),
	@LB_PERMITE_AUMENTO_CAPITAL BIT,
	@LS_REFERENCIA_AUX VARCHAR(20),
	@LM_VALOR_REFINANCIAR MONEY,
	@LM_VALOR_OTROS MONEY,
	@LM_CUOTAS MONEY,
	@LS_RUBRO CHAR(3),
	@LM_VALOR_PAGO_REFINANCIAMIENTO MONEY,
	@LM_VALOR_CXC_REFINANCIAMIENTO MONEY,
	@LM_VALOR_PAGO_RENOVACION MONEY,
	@LM_VALOR_CXC_RENOVACION MONEY
		

IF NOT EXISTS (	SELECT 1 
				FROM SL_MEDIO_APROB,SL_SOLICITUD,
				CR_RENOVACION
				WHERE 
				CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
				and map_solicitud = sol_solicitud
				and CR_RENOVACION.ren_credito = @AS_CREDITO
				and ren_estado = 'A')
BEGIN
		
	SET @AS_MSJ = 'EL CREDITO NO TIENE APROBADA UNA RENOVACION'
	RETURN -1

END 

SELECT @LI_SOLICITUD_NUEVA = sol_solicitud,
	@LI_RENOVACION = ren_id,
	@LS_FONDO = sol_fondo,
	@LS_SUB_FONDO = sol_subfondo,
	@LS_TIPO_OPERACION = sol_tipo_operacion,
	@LM_MONTO_SOL = sol_monto_solicitado
	FROM SL_MEDIO_APROB,SL_SOLICITUD,
	CR_RENOVACION
	WHERE 
	CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
	and map_solicitud = sol_solicitud
	and CR_RENOVACION.ren_credito = @AS_CREDITO
	and ren_estado = 'A'

		
SELECT @LS_RUBRO_K = rub_rubro FROM CR_RUBROS WHERE rub_es_capital = 1

IF @AB_RENOVACION_MANUAL = 1 AND @AB_RENOVACION_AUTOMATICA = 1
BEGIN
	SET @AS_MSJ = 'NO SE PUEDE REALIZAR UNA RENOVACION AUTOMATICA Y MANUAL A LA VEZ'
	RETURN -1
END 


IF @AB_RENOVACION_MANUAL = 0 AND @AB_RENOVACION_AUTOMATICA = 0
BEGIN
	SET @AS_MSJ = 'NO SE INDICA SI ES UNA RENOVACION AUTOMATICA O MANUAL'
	RETURN -1
END 

------------------------VALIDA SI PERMITE AUMENTO DE CAPITAL ----------------------------------------

	SELECT @LM_SALDO_CR = cre_saldo
	FROM CR_CREDITOS 
	WHERE cre_credito = @AS_CREDITO

	SELECT @LB_PERMITE_AUMENTO_CAPITAL = top_permite_aumento_capital
	FROM CR_TIPO_OPERACION
	WHERE top_tipo_operacion = @LS_TIPO_OPERACION

	SET @LM_SALDO_CR = ISNULL(@LM_SALDO_CR,0)
	SET @LM_MONTO_SOL = ISNULL(@LM_MONTO_SOL,0)
	
	IF (@LM_SALDO_CR  - @LM_MONTO_SOL ) <> 0 AND @LB_PERMITE_AUMENTO_CAPITAL = 0 
	BEGIN
		SET @AS_MSJ = 'ERROR REVISE SALDO DE CREDITO NO ES IGUAL AL DE LA SOLICITUD' 
		RETURN -1
	END 


-----------------------------------------------------------------


IF @AB_RENOVACION_MANUAL = 1 
BEGIN
	SELECT @LM_MONTO_RECIBIR = ren_monto_recibir,
	@LM_A_LIQUIDAR = ren_monto_liquidar
	FROM SL_MEDIO_APROB,
	CR_RENOVACION
	WHERE 
	CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
	and CR_RENOVACION.ren_credito = @AS_CREDITO  
	AND ren_estado = 'A'


	-- UNICAMENTE SE REALIZA LA VALIDACION
	-- SI EXISTE UN VALOR A LIQUIDAR, ES UNICAMENTE CUANDO DEBE PASAR
	-- POR CAJA
	
	IF @LM_A_LIQUIDAR > 0 
	BEGIN
		IF  ABS ( @AM_VALOR - (@AM_EFECTIVO + @AM_CHEQUE ) ) >= 0.01 AND @AS_TIPO_TRAN = dbo.f_obtener_parametro_s ('CRPG') 
		BEGIN
			SET @AS_MSJ = ' A EL VALOR DE LA TRANSACCIÓN DEBE SER IGUAL A LA SUMA DE EFECTIVO Y CHEQUE'
			RETURN -1
		END 
	
		-- VALIDACIÓN DE QUE PROCEDE LA RENOVACIÓN
		EXEC  @LI_RET = sp_cr_valida_pago_renovacion
				@AS_CREDITO = @AS_CREDITO ,
				@AM_PAGO = @AM_VALOR ,
				@AM_MONTO = @LM_RENOVACION OUT,
				@AM_SALDO = @LM_SALDO OUT,
				@AS_MSJ = @AS_MSJ OUT
		
			IF @LI_RET <> 1 RETURN -1 
	END
	
	IF @LM_A_LIQUIDAR = 0 AND @AM_VALOR > 0 
	BEGIN
		SET @AS_MSJ = 'REVISE EL VALOR DE LA TRANSACCIÓN'
		RETURN -1
	END 
	

	
	IF @LM_MONTO_RECIBIR > 0
	BEGIN 
		SELECT @LM_RENOVACION = SL_MEDIO_APROB.map_monto
		FROM SL_MEDIO_APROB,
		CR_RENOVACION
		WHERE 
		CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
		and CR_RENOVACION.ren_credito = @AS_CREDITO
		and ren_estado = 'A'
	
		SET @LM_RENOVACION = ISNULL(@LM_RENOVACION,0) 

		SELECT @LM_SALDO = SUM(cuo_saldo)
		FROM CR_CUOTAS, CR_RUBROS
		WHERE cuo_credito = @AS_CREDITO
		AND cuo_pagada = 0 
		AND rub_rubro = cuo_rubro
		AND cuo_saldo > 0
	
		SET @LM_SALDO = ISNULL(@LM_SALDO,0) 

		-- SI ES RENOVACION CON DESEMBOLSO 
		-- OBTENER LOS VALORES ANTERIORES
		IF @LS_TIPO_OPERACION = 'T'
		BEGIN
			SELECT @LM_VALORES_ANTERIORES = SUM(cuo_saldo)
			FROM CR_CUOTAS, CR_RUBROS
			WHERE cuo_credito = @AS_CREDITO
			AND cuo_pagada = 0 
			AND rub_rubro = cuo_rubro
			AND cuo_rubro != @LS_RUBRO_K 
			AND cuo_saldo > 0
		
		END
		ELSE		
			SELECT @LM_VALORES_ANTERIORES = 0
			
		SET @LM_VALORES_ANTERIORES = ISNULL(@LM_VALORES_ANTERIORES,0)

	END

	/*
	SELECT @LS_PRODUCTO = sol_producto
	FROM CR_RENOVACION, SL_SOLICITUD, CR_CREDITOS
	WHERE cre_credito = @AS_CREDITO 	
	AND ren_estado = 'A'
	AND sol_solicitud = ren_solicitud_ren   
	AND cre_credito = ren_credito


	IF (@LM_MONTO_RECIBIR = 0 AND dbo.f_cr_obtener_parametro_b(@LS_PRODUCTO,'BIT_RETANQUEO')= 1 )
	BEGIN 
		DECLARE @LB_TIPO_DES_MONCERO BIT

		SELECT @LB_TIPO_DES_MONCERO = ISNULL (dbo.f_cr_obtener_parametro_b(@LS_PRODUCTO,'BIT_TIPO_DES_MONCERO'),0)

		IF @LB_TIPO_DES_MONCERO = 1 AND @AS_TIPO_DESEMBOLSO = dbo.f_cr_obtener_parametro_s(@LS_PRODUCTO,'TIPO_DES_MONCERO')
		BEGIN

			SELECT @LM_RENOVACION = SL_MEDIO_APROB.map_monto
			FROM SL_MEDIO_APROB,
			 CR_RENOVACION
			WHERE 
			CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
			and CR_RENOVACION.ren_credito = @AS_CREDITO
		
			SET @LM_RENOVACION = ISNULL(@LM_RENOVACION,0) 
	
			SELECT @LM_SALDO = SUM(cuo_saldo)
			FROM CR_CUOTAS, CR_RUBROS
			WHERE cuo_credito = @AS_CREDITO
			AND cuo_pagada = 0 
			AND rub_rubro = cuo_rubro
			AND cuo_saldo > 0
		
			SET @LM_SALDO = ISNULL(@LM_SALDO,0) 
	
			SELECT @LM_VALORES_ANTERIORES = 0
		END
		ELSE
		BEGIN
			SET @AS_MSJ = 'TIPO DE DESEMBOLSO NO PERMITIDO'
			RETURN -1
		END 

	END
	*/
	IF (@LM_MONTO_RECIBIR = 0 AND ( @LS_TIPO_OPERACION = 'E' OR @LS_TIPO_OPERACION = 'F' OR @LS_TIPO_OPERACION = 'R') )---REESTRUCTURACION
	BEGIN 
	
			
		SELECT @LM_RENOVACION = SL_MEDIO_APROB.map_monto
		FROM SL_MEDIO_APROB,
		 CR_RENOVACION
		WHERE 
		CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
		and CR_RENOVACION.ren_credito = @AS_CREDITO

		SET @LM_RENOVACION = ISNULL(@LM_RENOVACION,0) 

				
		SELECT @LM_SALDO = SUM(cuo_saldo)
		FROM CR_CUOTAS, CR_RUBROS
		WHERE cuo_credito = @AS_CREDITO
		AND cuo_pagada = 0 
		AND rub_rubro = cuo_rubro
		AND cuo_saldo > 0

		SET @LM_SALDO = ISNULL(@LM_SALDO,0) --+ ISNULL(@LM_INTERES_ANTICIPADO,0)

		SELECT @LM_VALORES_ANTERIORES = 0

	END
END

IF @AB_RENOVACION_AUTOMATICA = 1 
BEGIN

	SELECT @LM_SALDO = SUM(cuo_saldo)
	FROM CR_CUOTAS, CR_RUBROS
	WHERE cuo_credito = @AS_CREDITO
	AND cuo_pagada = 0 
	AND rub_rubro = cuo_rubro
	AND cuo_saldo > 0

	SET @LM_SALDO = ISNULL(@LM_SALDO,0) 

	SELECT @LM_VALORES_ANTERIORES = SUM(cuo_saldo)
	FROM CR_CUOTAS, CR_RUBROS
	WHERE cuo_credito = @AS_CREDITO
	AND cuo_pagada = 0 
	AND rub_rubro = cuo_rubro
	AND cuo_rubro <> @LS_RUBRO_K
	AND cuo_saldo > 0

	SET @LM_VALORES_ANTERIORES = ISNULL(@LM_VALORES_ANTERIORES,0)

	SELECT @LM_RENOVACION = SL_MEDIO_APROB.map_monto
	FROM SL_MEDIO_APROB,
		 CR_RENOVACION
	WHERE 
	CR_RENOVACION.ren_solicitud_ren =  SL_MEDIO_APROB.map_solicitud
	and CR_RENOVACION.ren_credito = @AS_CREDITO

	SET @LM_RENOVACION = ISNULL(@LM_RENOVACION,0) 

END

SELECT @LI_SOLICITUD  =  ren_solicitud_ren, 
@LM_A_LIQUIDAR = ren_monto_liquidar 
FROM  CR_RENOVACION
WHERE ren_credito = @AS_CREDITO
AND ren_estado = 'A'

IF @LI_SOLICITUD   IS NULL OR @LI_SOLICITUD  = 0
BEGIN
	SET @AS_MSJ = 'REVISE NO SE ENCUENTRA LA RENOVACION ' + @AS_CREDITO
	RETURN -1 
END

/*
