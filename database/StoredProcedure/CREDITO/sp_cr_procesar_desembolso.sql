--	WHERE des_solicitud = @AI_SOLICITUD
--AND 

IF @AB_RENOVACION = 1 
	SET @LM_VALOR_PAGAR = @AM_VALOR_PAGAR 
ELSE
	SET @LM_VALOR_PAGAR = @LM_VALOR 

IF @LB_ES_AHORROS_CASH = 1 OR @LB_ES_AHORROS = 1 
BEGIN
		
	IF @LB_ES_AHORROS_CASH = 1
	BEGIN
	
		IF EXISTS (	SELECT 1
					FROM CL_CLIENTE 
					WHERE (cli_id = @LI_CLIENTE) and 
					(
						(cli_entidad_financiera is null or cli_tipo_cuenta is null or cli_numero_cuenta is null) OR 
						(LTRIM(RTRIM(cli_entidad_financiera)) = '' or LTRIM(RTRIM(cli_tipo_cuenta)) = '' or LTRIM(RTRIM(cli_numero_cuenta)) = '') 
					)
					)
		

		BEGIN
			SET @AS_MSJ = 'REVISE LOS DATOS DE LA CUENTA DEL BANCO DEL CLIENTE'
			RETURN -1
		END

	END 
	
		
	EXEC @LI_RET = sp_cr_desembolso_cuenta_ah 
					@AS_OFICINA = @AS_OFICINA,
					@AS_USUARIO = @AS_USUARIO ,
					@AI_SOLICITUD = @AI_SOLICITUD,
					@AS_CREDITO = @AS_CREDITO, 
					@AS_TIPO_DESEMBOLSO = @AS_TIPO_DESEMBOLSO, 
					@AS_MSJ = @AS_MSJ OUTPUT,
					@AI_TRA_ID = @LI_TRA_ID OUTPUT, 
					@AS_DOCUMENTO = @LS_DOCUMENTO OUTPUT,
					@AI_SEC = 1
		
	IF @LI_RET = -1 
		RETURN -1

	SET @LS_REFERENCIA = CONVERT(VARCHAR(20),@LI_TRA_ID)


	/*
	SELECT @LS_TIPO_TRANS = tds_tipo_trans_ah
	FROM CR_TIPO_DESEMBOLSO
	WHERE tds_tipo_desembolso = 'AH'

	
	EXEC @LI_RET = CUENTAS..sp_ah_insertar_transaccion
		@AS_CUENTA 	= @AS_REFERENCIA,
		@AS_TIPO_TRANS 	= @LS_TIPO_TRANS,
		@AS_OFICINA 	= @AS_OFICINA ,
		@AS_USUARIO	= @AS_USUARIO,
		@AM_VALOR 	= @LM_VALOR_PAGAR,
		@AS_REFERENCIA 	= @AS_CREDITO,
		@AS_REFERENCIA_CTA = NULL,
		@AM_EFECTIVO 	= 0,
		@AM_CHEQUE 	= 0,
		@AS_CONCEPTO 	= NULL,
		@AS_MSJ 	= @AS_MSJ OUTPUT,
		@AI_TRA_ID 	= @LI_TRA_ID OUTPUT
	IF @LI_RET = -1 
		RETURN -1
	*/
	

END 

ELSE
	IF @AS_TIPO_DESEMBOLSO = 'CC'
	BEGIN
		SELECT @LS_TIPO_TRANS = tds_tipo_trans_cc
		FROM CR_TIPO_DESEMBOLSO
		WHERE tds_tipo_desembolso = 'CC'

		EXEC @LI_RET = CUENTAS..sp_cc_insertar_transaccion
		@AS_CUENTA 	= @AS_REFERENCIA,
		@AS_TIPO_TRANS 	= @LS_TIPO_TRANS,
		@AS_OFICINA 	= @AS_OFICINA ,
		@AS_USUARIO 	= @AS_USUARIO,
		@AM_VALOR 	= @LM_VALOR_PAGAR,
		@AS_REFERENCIA 	= @AS_REFERENCIA,
		@AS_REFERENCIA_CTA = NULL,
		@AM_EFECTIVO 	= 0,
		@AM_CHEQUE 	= 0,
		@AS_CONCEPTO 	= NULL,
		@AS_MSJ 	= @AS_MSJ OUTPUT,
		@AI_TRA_ID 	= @LI_TRA_ID OUTPUT

		IF @LI_RET = -1 
			RETURN -1
	END

	ELSE
		IF @AS_TIPO_DESEMBOLSO = 'EF'
		BEGIN
			-- SI NO DESEMBOLSA COMPLETO SOLO ACTUALIZA PARA DESEMBOLSO EN EFECTIVO.... 
			RETURN 1
		END

EXEC @LI_RET = sp_cr_generar_descuentos_ahorros
	@AS_OFICINA = @AS_OFICINA,
	@AS_USUARIO = @AS_USUARIO,
	@AI_SOLICITUD = @AI_SOLICITUD,
	@AS_CREDITO = @AS_CREDITO,
	@AS_MSJ = @AS_MSJ OUTPUT,
	@AI_SEC = 1
 		
IF @LI_RET = -1 
	RETURN -1
	
EXEC @LI_RET = sp_cr_pagar_desembolso 
	@AS_CREDITO 	= @AS_CREDITO, 
	@AS_USUARIO 	= @AS_USUARIO,
	@AS_OFICINA 	= @AS_OFICINA,
	@AM_VALOR	= @LM_VALOR ,
	@AS_MSJ 	= @AS_MSJ OUTPUT,
	@AS_REFERENCIA	= @LS_REFERENCIA,
	@AS_DOCUMENTO   = @LS_DOCUMENTO,
	@AI_SEC			= 1


IF @LI_RET = -1 
	RETURN -1


------------------ PROCESO CASH COLATERAL ----------------------

IF @LB_CASH_COLATERAL = 1 AND @LB_PRECAN_CAP_DES = 1 
BEGIN 

	EXEC @LI_RET = sp_cr_proceso_cash_colateral @AS_USUARIO,@AS_OFICINA,@AI_SOLICITUD,@AS_MSJ OUT 

	IF @LI_RET <> 1
		RETURN -1
END

------------------ PROCESO CASH COLATERAL ----------------------

if @LI_CR_X_INTEGRANTE = 1 
	
	EXEC @LI_RET = sp_cr_generar_cartera_integrante
		@AS_CREDITO 	= @AS_CREDITO,
		@AS_USUARIO 	= @AS_USUARIO,
		@AS_MSJ 	= @AS_MSJ OUT,
		@AI_SEC = 1


else 
	
	EXEC @LI_RET = sp_cr_generar_cartera
		@AS_CREDITO 	= @AS_CREDITO,
		@AS_USUARIO 	= @AS_USUARIO,
		@AS_MSJ 	= @AS_MSJ OUT,
		@AI_SEC		= 1


IF @LI_RET = -1 
	RETURN -1

--  PAGO POR LOS DESCUENTOS QUE SE COBRAN 
--  LOS CUALES SE GENERAN COMO CUOTA CERO PERO UNICAMENTE SI SON RUBROS FINANCIADOS

---------------------------------------------------------------------------

IF EXISTS (SELECT 1 FROM CR_CUOTAS,SL_DESCUENTOS,CR_DESEMBOLSO
		WHERE cuo_credito = @AS_CREDITO AND 
		cuo_credito = CR_DESEMBOLSO.des_credito AND
		CR_DESEMBOLSO.des_solicitud = SL_DESCUENTOS.des_solicitud AND
		CR_DESEMBOLSO.des_sec = 1 AND
		SL_DESCUENTOS.des_rubro_cuota_desembolso = cuo_rubro AND
		SL_DESCUENTOS.des_es_financiado = 1 AND
		cuo_num_cuota = 0 )
BEGIN
	
	SELECT @LM_SALDO_CUOTA_CERO = SUM(cuo_saldo)
	FROM CR_CUOTAS,SL_DESCUENTOS,CR_DESEMBOLSO
	WHERE cuo_credito = @AS_CREDITO AND 
	cuo_credito = CR_DESEMBOLSO.des_credito AND
	CR_DESEMBOLSO.des_solicitud = SL_DESCUENTOS.des_solicitud AND
	CR_DESEMBOLSO.des_sec = 1 AND
	SL_DESCUENTOS.des_rubro_cuota_desembolso = cuo_rubro AND
	SL_DESCUENTOS.des_es_financiado = 1 AND
	cuo_num_cuota = 0 
	
	SET @LM_SALDO_CUOTA_CERO = ISNULL(@LM_SALDO_CUOTA_CERO,0) 
	
	EXEC @LI_RET = sp_cr_tipo_trans_pago_caja 
			@AS_TIPO_TRAN = @LS_TIPO_TRAN OUT
	
	SET @LM_EFECTIVO = @LM_SALDO_CUOTA_CERO
	SET @LM_CHEQUE = 0
	SET @LS_TIPO_TRAN = 'RSE'
	
	IF @LM_SALDO_CUOTA_CERO > 0 
	BEGIN
	
		EXEC @LI_RET =  sp_cr_inserta_transaccion_cr
				@AS_CREDITO = @AS_CREDITO,
				@AS_TIPO_TRANS = @LS_TIPO_TRAN ,
				@AS_MONEDA = @LS_MONEDA ,
				@AM_VALOR = @LM_SALDO_CUOTA_CERO,
				@AM_EFECTIVO = @LM_EFECTIVO,
				@AM_CHEQUE = @LM_CHEQUE,
				@AS_OFICINA = @AS_OFICINA,
				@AS_USUARIO = @AS_USUARIO ,
				@AS_MSJ = @AS_MSJ   OUTPUT,
				@AI_TRAN = @LI_TRAN OUTPUT,
				@AB_ABONO_RECALCULO = 0
	
		IF @LI_RET <> 1 
			RETURN -1 
	
	END
END

