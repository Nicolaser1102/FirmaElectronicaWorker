CREATE  OR ALTER PROCEDURE [dbo].[sp_cr_procesar_desembolso]
@AS_USUARIO VARCHAR(15),
@AS_OFICINA CHAR(4),
@AI_SOLICITUD INT,
@AS_TIPO_DESEMBOLSO CHAR(3),
@AS_REFERENCIA VARCHAR(20),
@AS_FONDO CHAR(3),
@AS_SUBFONDO CHAR(3) = NULL,
@ADT_FECHA_DES DATETIME,
@ADT_FECHA_1ER_PG DATETIME ,
@ADEC_TASA DECIMAL ( 18, 4 ),
@AB_RENOVACION BIT = 0,
@AM_VALOR_PAGAR MONEY = 0,
@AI_ENTIDAD_FINANCIERA INTEGER = NULL,
@AS_TIPO_CUENTA CHAR(1)= NULL,
@AS_NUMERO_CUENTA VARCHAR(20) = NULL,
@AS_CREDITO VARCHAR(20) = NULL OUTPUT,
@AS_MSJ VARCHAR(100) OUTPUT,
@AS_XML_DESEMBOLSO VARCHAR(8000) = NULL
AS
BEGIN

DECLARE @LI_RET INT, 
	@LM_VALOR_PAGAR MONEY, 
	@LM_VALOR MONEY, 
	@LS_TIPO_TRANS CHAR(3), 
	@LI_TRA_ID INT,
	@LS_PRODUCTO VARCHAR (5),
	@LI_NRO_CP INTEGER,
	@AI_TIPO INTEGER,
	@LS_REFERENCIA VARCHAR(20),
	@LS_DOCUMENTO VARCHAR(20),
	@LS_TIPO_TRAN VARCHAR(3),
	@LS_MONEDA CHAR(1),
	@LM_SALDO_CUOTA_CERO MONEY,
	@LM_EFECTIVO MONEY,
	@LM_CHEQUE MONEY,
	@LI_TRAN INTEGER,
	@LS_TIPO_OPERACION CHAR(1),
	@LB_PERMITE_AUMENTO_CAPITAL BIT, 
	@LI_ES_GRUPAL BIT,
	@LI_CR_X_INTEGRANTE BIT ,
	@LS_SUBFONDO VARCHAR(3),
	@LD_TASA_MORA DECIMAL(8,2), 
	@LB_ES_AHORROS_CASH BIT,
	@LB_ES_AHORROS BIT,
	@LI_CLIENTE INT,
	@LB_DESEMBOLSO_PARCIAL BIT,
	@LB_FECHA_POST_DESEM BIT,
	@LB_CUALQ_FECHA_OTOR_CCA BIT,
	@LDT_FECHA_OTORGAMIENTO DATETIME, 
	@LB_PRECAN_CAP_DES BIT, 
	@LB_CASH_COLATERAL BIT,
	@LB_CREA_CUETA_AH_CR BIT,
	@LS_CUETA_AH_CR VARCHAR(20),
	@LS_CUENTA VARCHAR(20), 
	@LS_NOMBRE VARCHAR(30)
	
	DECLARE @TIPO_DESEMBOLSO TABLE
	(

	secuencial integer identity,
	sec integer, 
	tipo_desemb varchar(3),
	valor money
	)


	DECLARE	@LT_DESEMBOLSO TABLE (sec int, tipo_desembolso char(3), fecha_otorgamiento datetime, monto money, referencia varchar(20), entidad_financiera int, tipo_cuenta char(1),numero_cuenta varchar(20)) 




SELECT @LS_PRODUCTO = sol_producto,
@LS_MONEDA = sol_moneda,
@LS_TIPO_OPERACION = sol_tipo_operacion,
@LI_ES_GRUPAL = sol_por_grupo,
@LI_CR_X_INTEGRANTE = dbo.f_cr_obtener_parametro_b(sol_producto,'BIT_CREDITO_INTEGRAN'), 
@LB_PERMITE_AUMENTO_CAPITAL = top_permite_aumento_capital,
@LB_FECHA_POST_DESEM = dbo.f_cr_obtener_parametro_b(sol_producto,'BIT_FECHA_POST_DESEM'),
@LB_CUALQ_FECHA_OTOR_CCA = dbo.f_cr_obtener_parametro_b(sol_producto,'CCA_CUALQ_FECH_OTOR'), --PARA QUE NO VALIDE FECHA OTORGAMIENTO POR COMPRA DE CARTERA
@LI_CLIENTE = sol_cliente,
@LB_DESEMBOLSO_PARCIAL = sol_desembolso_parcial,
@LDT_FECHA_OTORGAMIENTO = sol_fecha_otorgamiento,
@LB_PRECAN_CAP_DES = dbo.f_cr_obtener_parametro_b(sol_producto,'PRECAN_CAP_DES_CASH'),
@LB_CASH_COLATERAL =  dbo.f_cr_obtener_parametro_b(sol_producto,'ES_CASH_COLATERAL'),
@LB_CREA_CUETA_AH_CR = dbo.f_cr_obtener_parametro_b(sol_producto,'BIT_CTA_RECUP_AH_CR')
FROM SL_SOLICITUD,CR_TIPO_OPERACION
WHERE sol_solicitud = @AI_SOLICITUD
AND sol_tipo_operacion = top_tipo_operacion 

SET @LB_CUALQ_FECHA_OTOR_CCA = ISNULL(@LB_CUALQ_FECHA_OTOR_CCA,0)


IF @LB_DESEMBOLSO_PARCIAL = 1 
BEGIN
	INSERT INTO @LT_DESEMBOLSO 
	(sec,tipo_desembolso,fecha_otorgamiento, monto, referencia , entidad_financiera , tipo_cuenta ,numero_cuenta )
	EXEC dbo.sp_cr_listar_desembolso_detalle
	@AI_SOLICITUD = @AI_SOLICITUD ,
	@AS_XML_DESEMBOLSO = @AS_XML_DESEMBOLSO 
	
	IF NOT EXISTS (SELECT 1 FROM @LT_DESEMBOLSO WHERE sec = 1  )
	BEGIN
		SET @AS_MSJ  = 'NO SE HA DETERMINADO LOS DESEMBOLSOS PARCIALES'
		RETURN -1
	END
	
	SELECT @AS_TIPO_DESEMBOLSO = tipo_desembolso,
	@AM_VALOR_PAGAR = monto,
	@AS_REFERENCIA  = referencia,
	@AI_ENTIDAD_FINANCIERA = entidad_financiera,
	@AS_TIPO_CUENTA =  tipo_cuenta,
	@AS_NUMERO_CUENTA = numero_cuenta
	FROM @LT_DESEMBOLSO 
	WHERE sec = 1
	AND fecha_otorgamiento = @ADT_FECHA_DES

END

	IF NOT EXISTS (SELECT * FROM CR_TIPO_DESEMBOLSO WHERE tds_tipo_desembolso = @AS_TIPO_DESEMBOLSO AND tds_estado = 'A')
	BEGIN
		SET @AS_MSJ  = 'EL TIPO DE DESEMBOLSO NO EXISTE O NO ESTA ACTIVO'
		RETURN -1
	END


SELECT @LB_ES_AHORROS_CASH = tds_es_ahorros_cash,
@LB_ES_AHORROS = tds_es_ahorros
FROM CR_TIPO_DESEMBOLSO
WHERE tds_tipo_desembolso = @AS_TIPO_DESEMBOLSO 


IF (@LS_SUBFONDO IS NULL)
BEGIN
	SELECT @LS_SUBFONDO = sol_subfondo FROM SL_SOLICITUD
	WHERE sol_solicitud = @AI_SOLICITUD
END

IF @LB_FECHA_POST_DESEM = 1 AND @LB_CUALQ_FECHA_OTOR_CCA = 0 --PARA QUE NO VALIDE FECHA OTORGAMIENTO POR COMPRA DE CARTERA
BEGIN
	
	IF @ADT_FECHA_DES < dbo.FechaSistema()
	BEGIN
		SET @AS_MSJ  = 'FECHA DE DESEMBOLSO DEBE SER MAYOR O IGUAL A LA FECHA DEL SISTEMA'
		RETURN -1
	END
END 
ELSE 
BEGIN
	
	IF @ADT_FECHA_DES <> dbo.FechaSistema() AND @LB_CUALQ_FECHA_OTOR_CCA = 0 --PARA QUE NO VALIDE FECHA OTORGAMIENTO POR COMPRA DE CARTERA
	BEGIN
		SET @AS_MSJ  = 'FECHA DE DESEMBOLSO DEBE SER IGUAL A LA FECHA DEL SISTEMA'
		RETURN -1
	END
	
	IF dbo.FechaSistema() <> @LDT_FECHA_OTORGAMIENTO AND @LB_CUALQ_FECHA_OTOR_CCA = 0 --PARA QUE NO VALIDE FECHA OTORGAMIENTO POR COMPRA DE CARTERA
	BEGIN
		SET @AS_MSJ  = 'FECHA DE OTORGAMIENTO DE LA SOLICITUD DEBE SER IGUAL A LA FECHA DEL SISTEMA'
		RETURN -1
	END
	
	IF @ADT_FECHA_DES <> @LDT_FECHA_OTORGAMIENTO
	BEGIN
		SET @AS_MSJ  = 'FECHA DE OTORGAMIENTO DE LA SOLICITUD DEBE SER IGUAL A LA FECHA DEL SISTEMA (1)'
		RETURN -1
	END
	
END 


IF ( SELECT pro_permite_f1er_pg 
		FROM CR_PRODUCTOS 
		WHERE pro_producto = @LS_PRODUCTO ) = 1
BEGIN	
	IF @ADT_FECHA_DES > @ADT_FECHA_1ER_PG
	BEGIN
		SET @AS_MSJ  = 'FECHA DE PRIMER PAGO DEBE SER MAYOR AL OTORGAMIENTO'
		RETURN -1
	END

	IF ( SELECT pro_dmin_f1er_pg 
			FROM CR_PRODUCTOS 
			WHERE pro_producto = @LS_PRODUCTO ) > DATEDIFF ( dd, @ADT_FECHA_DES , @ADT_FECHA_1ER_PG )  
	BEGIN
		SET @AS_MSJ  = 'FECHA DE PRIMER PAGO NO VALIDA (MUY CERCANA A LA FECHA DE OTORGAMIENTO)'
		RETURN -1
	END

	IF ( SELECT pro_dmax_f1er_pg 
			FROM CR_PRODUCTOS 
			WHERE pro_producto = @LS_PRODUCTO ) < DATEDIFF ( dd, @ADT_FECHA_DES , @ADT_FECHA_1ER_PG )  
	BEGIN
		SET @AS_MSJ  = 'FECHA DE PRIMER PAGO NO VALIDA (MUY LEJANA A LA FECHA DE OTORGAMIENTO)'
		RETURN -1
	END
END

-- VALIDAD DATOS DE ENTIDAD FINANCIERA PARA ORDEN DE PAGO EN EFECTIVO 
IF @AS_TIPO_DESEMBOLSO = 'OPE' AND @AI_ENTIDAD_FINANCIERA IS NULL
BEGIN
		SET @AS_MSJ  = 'PARA ORDEN DE PAGO EN EFECTIVO DEBE INGRESAR LA ENTIDAD FINANCIERA'
		RETURN -1
END

-- VALIDAD DATOS DE ENTIDAD FINANCIERA PARA ORDEN DE PAGO EN CHEQUE
IF @AS_TIPO_DESEMBOLSO = 'OPC'
BEGIN
	IF @AI_ENTIDAD_FINANCIERA IS NULL
	BEGIN
		SET @AS_MSJ  = 'PARA ORDEN DE PAGO EN CHEQUE DEBE INGRESAR LA ENTIDAD FINANCIERA'
		RETURN -1
	END	
	
	IF @AS_TIPO_CUENTA  IS NULL
	BEGIN
		SET @AS_MSJ  = 'PARA ORDEN DE PAGO EN CHEQUE DEBE INGRESAR EL TIPO DE CUENTA'
		RETURN -1
	END	
	
	IF @AS_NUMERO_CUENTA  IS NULL
	BEGIN
		SET @AS_MSJ  = 'PARA ORDEN DE PAGO EN CHEQUE DEBE INGRESAR EL NUMERO DE CUENTA'
		RETURN -1
	END	
END

IF @AS_TIPO_DESEMBOLSO IN( 'OPC','OPE')
BEGIN
	IF NOT EXISTS (SELECT 1 FROM CR_ENTIDAD_FINANCIERA_TIPO_DES WHERE etd_entidad_financiera = @AI_ENTIDAD_FINANCIERA  AND etd_tipo_desemboslo = @AS_TIPO_DESEMBOLSO) 
	BEGIN 
		SET @AS_MSJ  = 'ENTIDAD FINANCIERA NO PERMITIDA PARA ESTE TIPO DE DESEMBOLSO'
		RETURN -1
	END
END

-- VALIDAR NUMERO DE CREDITOS VIGENTES EN PROCESO DE DESEMBOLSO
IF dbo.f_cr_obtener_parametro_b(@LS_PRODUCTO,'BIT_VALIDA_CR_DES') = 1
BEGIN
	EXEC @LI_RET = sp_sl_validacion_nro_creditos @AI_SOLICITUD ,@AS_MSJ OUTPUT,@AI_TIPO OUTPUT
	IF @LI_RET = -1 
		RETURN -1
END

--VALIDACION TASA EFECTIVA
DECLARE 
@LI_TIPO INTEGER

EXEC @LI_RET = sp_sl_validacion_tasa_efectiva_maxima @AI_SOLICITUD ,@AS_MSJ OUTPUT,@LI_TIPO OUTPUT

IF @LI_RET = -1
BEGIN 
	RETURN -1
END


UPDATE SL_SOLICITUD 
SET sol_fecha_1er_pg = @ADT_FECHA_1ER_PG,
sol_fecha_otorgamiento = @ADT_FECHA_DES
WHERE sol_solicitud = @AI_SOLICITUD


EXEC @LI_RET = sp_sl_actualizar_tasa_solicitud @AI_SOLICITUD, @ADEC_TASA

IF @LI_RET = -1 
BEGIN
	SET @AS_MSJ = 'ERROR AL ACTUALIZAR TASA EN LA SOLICITUD'
	RETURN -1
END

IF @AB_RENOVACION = 1
BEGIN
	
	DECLARE @LS_TIPO_DESEMBOLSO CHAR(3), @LS_ESTADO_DESEMBOLSO CHAR(1), @LB_TIPO_DES_MONCERO BIT

	SELECT @LB_TIPO_DES_MONCERO = ISNULL (dbo.f_cr_obtener_parametro_b(@LS_PRODUCTO,'BIT_TIPO_DES_MONCERO'),0)

	
	IF  @LB_TIPO_DES_MONCERO = 1 AND @AS_TIPO_DESEMBOLSO = dbo.f_cr_obtener_parametro_s(@LS_PRODUCTO,'TIPO_DES_MONCERO')
	BEGIN
		SET @LS_TIPO_DESEMBOLSO = @AS_TIPO_DESEMBOLSO 

		SELECT @LS_ESTADO_DESEMBOLSO = est_estado 
		FROM SL_ESTADO
		WHERE est_es_desembolsado = 1
	END
	ELSE
	BEGIN
	
		IF @LB_PERMITE_AUMENTO_CAPITAL = 1  OR @LS_TIPO_OPERACION = 'E' OR @LS_TIPO_OPERACION = 'F'
		BEGIN
			SET @LS_TIPO_DESEMBOLSO = @AS_TIPO_DESEMBOLSO 
			
			SELECT @LS_ESTADO_DESEMBOLSO = est_estado 
			FROM SL_ESTADO
			WHERE est_es_desembolsado = 1

		END
		ELSE 
		BEGIN 
			EXEC @LI_RET =  sp_cr_obtener_tipo_estado_desembolso
			@AS_TIPO_DESEMBOLSO = @LS_TIPO_DESEMBOLSO  OUTPUT,
			@AS_ESTADO_DESEMBOLSO = @LS_ESTADO_DESEMBOLSO OUTPUT
			--IF @LI_RET <> 1 RETURN -1 
		END
	
	END

END
ELSE
	SET @LS_TIPO_DESEMBOLSO = @AS_TIPO_DESEMBOLSO 
/*	
EXEC @LI_RET  = sp_cr_desembolso_insertar
	@AL_SOLICITUD 	= @AI_SOLICITUD,
	@AS_USUARIO 	= @AS_USUARIO,
	@AS_TIPO_DESEMBOLSO = @LS_TIPO_DESEMBOLSO,
	@AS_REFERENCIA 	= @AS_REFERENCIA,
	@AS_FONDO 	= @AS_FONDO,
	@AS_SUBFONDO = @AS_SUBFONDO,
	@ADT_FECHA_DESC = @ADT_FECHA_DES,
	@AI_ENTIDAD_FINANCIERA = @AI_ENTIDAD_FINANCIERA,
	@AS_TIPO_CUENTA = @AS_TIPO_CUENTA,
	@AS_NUMERO_CUENTA = @AS_NUMERO_CUENTA,
	@AS_CREDITO 	= @AS_CREDITO OUT,
	@AM_VALOR_PAGAR = @LM_VALOR OUT,
	@AS_MSJ 	= @AS_MSJ OUTPUT 


IF @LI_RET = -1 
	RETURN -1
*/


EXEC @LI_RET = dbo.sp_cr_insertar_desembolso_detalle
@AI_SOLICITUD = @AI_SOLICITUD,
@AS_USUARIO = @AS_USUARIO,
@AS_TIPO_DESEMBOLSO = @LS_TIPO_DESEMBOLSO,
@AS_REFERENCIA =@AS_REFERENCIA,
@AS_FONDO = @AS_FONDO,
@AS_SUBFONDO = @AS_SUBFONDO,
@ADT_FECHA_DES = @ADT_FECHA_DES,
@AI_ENTIDAD_FINANCIERA = @AI_ENTIDAD_FINANCIERA,
@AS_TIPO_CUENTA = @AS_TIPO_CUENTA,
@AS_NUMERO_CUENTA = @AS_NUMERO_CUENTA,
@AS_XML_DESEMBOLSO = @AS_XML_DESEMBOLSO,
@AS_CREDITO = @AS_CREDITO  OUT,
@AM_VALOR_PAGAR = @LM_VALOR  OUT,
@AS_MSJ = @AS_MSJ  OUT

-- ACTUALIZA EL MONTO A LIQUIDAR SI CREDITO GRUPAL
-- ESTA ACTUALIZACION TAMBIEN SE REALIZA CUANDO SE PROCESA LA APROBACION
-- PERO PUEDEN EXISTIR PRODUCTOS QUE NO REQUIEREN APROBACION.
EXEC @LI_RET = sp_sl_actualizar_monto_liquidar
		@AI_SOLICITUD = @AI_SOLICITUD,
		@AS_USUARIO = @AS_USUARIO,
		@AS_MSJ = @AS_MSJ  OUTPUT


IF @LI_RET = -1  
	RETURN -1 

--INSERT @TIPO_DESEMBOLSO
